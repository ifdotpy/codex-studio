"""Generate or check schemas for the persisted formats read by the runtime."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from codex_agent_modes import (
    DEFAULT_GLOBAL_CONCURRENCY,
    DEFAULT_MAX_TEAM_AGENTS,
    DEFAULT_SUBAGENT_CONCURRENCY,
    LEAD_TEAM_RECORDS,
    MAX_SUBAGENT_CONCURRENCY,
    MAX_TEAM_AGENTS,
    MIN_GLOBAL_CONCURRENCY,
    MIN_SUBAGENT_CONCURRENCY,
    MIN_TEAM_AGENTS,
    QUEUED_WORKER_HEADROOM,
    TEAM_AGENT_HEADROOM,
)
from codex_layout import REPOSITORY_ROOT
from studio_api.persisted_models import STATE_SCHEMA_MODELS, state_schema_document


OUTPUT_ROOT = REPOSITORY_ROOT / "workspaces/runtime/packages/runtime-schema/src/schemas"
RUST_LIMITS_OUTPUT = REPOSITORY_ROOT / "workspaces/runtime/packages/runtime-schema/src/agent_limits_generated.rs"


def generated_schemas() -> dict[Path, object]:
    return {
        OUTPUT_ROOT / name: state_schema_document(model)
        for name, model in STATE_SCHEMA_MODELS.items()
    }


def render_rust_agent_limits() -> str:
    """Render Rust consumers from the Python runtime's authoritative limits."""
    return "\n".join(
        [
            "//! Generated by `studio_api.generate_state_schemas`; do not edit.",
            "//! Source: `codex_agent_modes.py`.",
            f"pub const MIN_SUBAGENT_CONCURRENCY: i64 = {MIN_SUBAGENT_CONCURRENCY};",
            f"pub const DEFAULT_SUBAGENT_CONCURRENCY: i64 = {DEFAULT_SUBAGENT_CONCURRENCY};",
            f"pub const MAX_SUBAGENT_CONCURRENCY: i64 = {MAX_SUBAGENT_CONCURRENCY};",
            f"pub const MIN_TEAM_AGENTS: i64 = {MIN_TEAM_AGENTS};",
            f"pub const DEFAULT_MAX_TEAM_AGENTS: i64 = {DEFAULT_MAX_TEAM_AGENTS};",
            f"pub const MAX_TEAM_AGENTS: usize = {MAX_TEAM_AGENTS};",
            f"pub const LEAD_TEAM_RECORDS: i64 = {LEAD_TEAM_RECORDS};",
            f"pub const QUEUED_WORKER_HEADROOM: i64 = {QUEUED_WORKER_HEADROOM};",
            f"pub const TEAM_AGENT_HEADROOM: i64 = {TEAM_AGENT_HEADROOM};",
            f"pub const MIN_GLOBAL_CONCURRENCY: i64 = {MIN_GLOBAL_CONCURRENCY};",
            f"pub const DEFAULT_GLOBAL_CONCURRENCY: i64 = {DEFAULT_GLOBAL_CONCURRENCY};",
            "pub const MAX_TRANSFER_AGENT_RECORDS: usize = MAX_TEAM_AGENTS;",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write committed schemas")
    mode.add_argument("--check", action="store_true", help="fail when committed schemas are stale")
    args = parser.parse_args(argv)
    generated: dict[Path, object] = generated_schemas()
    generated[RUST_LIMITS_OUTPUT] = render_rust_agent_limits()
    for path, expected in generated.items():
        try:
            content = path.read_text(encoding="utf-8") if path.exists() else None
            current = (
                content
                if isinstance(expected, str)
                else json.loads(content) if content is not None else None
            )
        except (OSError, UnicodeError, json.JSONDecodeError):
            current = None
        if args.check:
            if current != expected:
                print(f"{path.relative_to(REPOSITORY_ROOT)} is stale; run `pnpm run state-schemas:generate`", file=sys.stderr)
                return 1
        else:
            if current == expected:
                continue
            output = (
                expected
                if isinstance(expected, str)
                else json.dumps(expected, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
            )
            path.write_text(output, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
