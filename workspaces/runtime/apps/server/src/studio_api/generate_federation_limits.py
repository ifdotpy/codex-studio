"""Generate Rust federation limits from their Python owner."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from codex_layout import REPOSITORY_ROOT
from codex_federation_limits import (
    FEDERATION_BODY_LIMIT,
    FEDERATION_PATHS,
    MAX_BATCH_BYTES,
    MAX_BATCH_ITEMS,
    MAX_MESSAGE_CODEPOINTS,
    MAX_QUEUE_BYTES,
    MAX_QUEUE_ROWS,
    MAX_ROOM_RATE,
    MAX_ROOM_MEMBERS,
    PROTOCOL_VERSION,
)


RUST_OUTPUT = REPOSITORY_ROOT / "workspaces/runtime/packages/runtime-services/src/federation_limits.rs"
PYTHON_OUTPUT = REPOSITORY_ROOT / "workspaces/runtime/apps/server/src/codex_federation_protocol_generated.py"
RUST_EXPECTED = (
    "// Generated by studio_api.generate_federation_limits.\n"
    f"pub const MAX_MESSAGE_CODEPOINTS: usize = {MAX_MESSAGE_CODEPOINTS};\n"
    f"pub const MAX_BATCH_ITEMS: usize = {MAX_BATCH_ITEMS};\n"
    f"pub const MAX_BATCH_BYTES: usize = {MAX_BATCH_BYTES};\n"
    f"pub const MAX_ROOM_MEMBERS: usize = {MAX_ROOM_MEMBERS};\n"
    f"pub const MAX_QUEUE_ROWS: u64 = {MAX_QUEUE_ROWS};\n"
    f"pub const MAX_QUEUE_BYTES: u64 = {MAX_QUEUE_BYTES};\n"
    f"pub const MAX_ROOM_RATE: u64 = {MAX_ROOM_RATE};\n"
    f"pub const PROTOCOL_VERSION: u64 = {PROTOCOL_VERSION};\n"
    f"pub const FEDERATION_BODY_LIMIT: usize = {FEDERATION_BODY_LIMIT};\n"
    f"pub const FEDERATION_PATHS: [&str; {len(FEDERATION_PATHS)}] = [\n"
    + "".join(f"    {json.dumps(path)},\n" for path in FEDERATION_PATHS)
    + "];\n"
)
PYTHON_EXPECTED = (
    "from typing import Literal\n\n"
    "# Generated by studio_api.generate_federation_limits.\n"
    f"FederationProtocolVersion = Literal[{PROTOCOL_VERSION}]\n"
)
OUTPUTS = {RUST_OUTPUT: RUST_EXPECTED, PYTHON_OUTPUT: PYTHON_EXPECTED}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write generated federation contracts")
    mode.add_argument("--check", action="store_true", help="fail when generated federation contracts are stale")
    args = parser.parse_args(argv)
    for path, expected in OUTPUTS.items():
        if args.check:
            try:
                current = path.read_text(encoding="utf-8")
            except (OSError, UnicodeError):
                current = None
            if current != expected:
                print(
                    f"{path.relative_to(REPOSITORY_ROOT)} is stale; "
                    "run `pnpm run federation-limits:generate`",
                    file=sys.stderr,
                )
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
