def _entity_aliases(names: list[str], include_sync_entity_payload: bool = False) -> str:
    aliases = "".join(
        f'\nexport type {name} = components["schemas"]["{name}"];'
        for name in names
    )
    if include_sync_entity_payload:
        aliases += '\nexport type SyncEntityPayload = components["schemas"]["SyncEntityPayload"];'
    return aliases


def _sync_protocol_version(document: dict[str, JsonValue]) -> int:
    components = document.get("components")
    schemas = components.get("schemas") if isinstance(components, dict) else None
    response = schemas.get("SyncProtocolResponse") if isinstance(schemas, dict) else None
    properties = response.get("properties") if isinstance(response, dict) else None
    protocol = properties.get("protocolVersion") if isinstance(properties, dict) else None
    versions = properties.get("supportedVersions") if isinstance(properties, dict) else None
    protocol_value = _single_schema_value(protocol)
    versions_items = versions.get("items") if isinstance(versions, dict) else None
    supported_value = _single_schema_value(versions_items)
    if protocol_value != SYNC_PROTOCOL_VERSION or supported_value != SYNC_PROTOCOL_VERSION:
        raise ValueError("SyncProtocolResponse must use the shared single supported version")
    return SYNC_PROTOCOL_VERSION


def _single_schema_value(schema: object) -> object:
    if not isinstance(schema, dict):
        return None
    if "const" in schema:
        return schema["const"]
    values = schema.get("enum")
    return values[0] if isinstance(values, list) and len(values) == 1 else None


def render_sync_protocol_rust(document: dict[str, JsonValue]) -> str:
    version = _sync_protocol_version(document)
    return (
        "// Generated from the Pydantic SyncProtocolResponse contract.\n"
        f"pub const SYNC_PROTOCOL_VERSION: u32 = {version};\n"
        f"pub const SYNC_PROTOCOL_VERSION_TEXT: &str = {json.dumps(str(version))};\n"
        f"pub const SYNC_ENTITY_SCOPE: &str = {json.dumps(SYNC_ENTITY_SCOPE)};\n"
    )


def render_sync_protocol_python(document: dict[str, JsonValue]) -> str:
    version = _sync_protocol_version(document)
    return (
        "from typing import Literal, TypeAlias\n\n"
        "# Generated by studio_api.generate_types; do not edit.\n"
        f"SyncProtocolVersion: TypeAlias = Literal[{version}]\n"
    )


def render_sync_protocol_typescript(document: dict[str, JsonValue]) -> str:
    return (
        f"export const SYNC_PROTOCOL_VERSION = {_sync_protocol_version(document)} as const;\n"
        f"export const SYNC_ENTITY_SCOPE = {json.dumps(SYNC_ENTITY_SCOPE)} as const;"
    )


def render_sync_protocol_node(document: dict[str, JsonValue]) -> str:
    return (
        "// Generated by studio_api.generate_types; do not edit.\n"
        f"export const SYNC_ENTITY_SCOPE = {json.dumps(SYNC_ENTITY_SCOPE)};\n"
    )


def _token_rate_max_entries(document: dict[str, JsonValue]) -> int:
    components = document.get("components")
    schemas = components.get("schemas") if isinstance(components, dict) else None
    snapshot = schemas.get("TokenRateSnapshot") if isinstance(schemas, dict) else None
    properties = snapshot.get("properties") if isinstance(snapshot, dict) else None
    rates = properties.get("rates") if isinstance(properties, dict) else None
    teams = properties.get("teams") if isinstance(properties, dict) else None
    team_members = teams.get("additionalProperties") if isinstance(teams, dict) else None
    limits = (
        rates.get("maxProperties") if isinstance(rates, dict) else None,
        teams.get("maxProperties") if isinstance(teams, dict) else None,
        team_members.get("maxProperties") if isinstance(team_members, dict) else None,
    )
    maximum = limits[0]
    if (
        not isinstance(maximum, int)
        or isinstance(maximum, bool)
        or maximum <= 0
        or any(type(limit) is not int or limit != maximum for limit in limits[1:])
    ):
        raise ValueError("TokenRateSnapshot must define one shared positive maxProperties limit")
    return maximum


def _token_rate_identifier_max_codepoints(document: dict[str, JsonValue]) -> int:
    components = document.get("components")
    schemas = components.get("schemas") if isinstance(components, dict) else None
    value = schemas.get("TokenRateValue") if isinstance(schemas, dict) else None
    properties = value.get("properties") if isinstance(value, dict) else None
    turn_id = properties.get("turnId") if isinstance(properties, dict) else None
    maximum = turn_id.get("maxLength") if isinstance(turn_id, dict) else None
    rates = schemas.get("TokenRateSnapshot") if isinstance(schemas, dict) else None
    snapshot_properties = rates.get("properties") if isinstance(rates, dict) else None
    rate_map = snapshot_properties.get("rates") if isinstance(snapshot_properties, dict) else None
    teams = snapshot_properties.get("teams") if isinstance(snapshot_properties, dict) else None
    team_map = teams.get("additionalProperties") if isinstance(teams, dict) else None
    identifier_schemas = (
        rate_map.get("propertyNames") if isinstance(rate_map, dict) else None,
        teams.get("propertyNames") if isinstance(teams, dict) else None,
        team_map.get("propertyNames") if isinstance(team_map, dict) else None,
    )
    if (
        type(maximum) is not int
        or maximum <= 0
        or not isinstance(turn_id, dict)
        or type(turn_id.get("minLength")) is not int
        or turn_id["minLength"] != 1
        or any(
            not isinstance(identifier_schema, dict)
            or type(identifier_schema.get("minLength")) is not int
            or identifier_schema["minLength"] != 1
            or type(identifier_schema.get("maxLength")) is not int
            or identifier_schema["maxLength"] != maximum
            for identifier_schema in identifier_schemas
        )
    ):
        raise ValueError("Token-rate identifiers must share one positive maxLength")
    return maximum


def render_token_rate_limits(document: dict[str, JsonValue]) -> str:
    maximum = _token_rate_max_entries(document)
    identifier_max = _token_rate_identifier_max_codepoints(document)
    if MAX_TOKEN_RATE_TOTAL_ENTRIES != maximum * 2:
        raise ValueError("Token-rate aggregate limit must cover two per-agent views")
    return (
        "// Generated from the Pydantic TokenRateSnapshot contract.\n"
        f"pub const TOKEN_RATE_MAX_ENTRIES: usize = {maximum};\n"
        f"pub const TOKEN_RATE_MAX_TOTAL_ENTRIES: usize = {MAX_TOKEN_RATE_TOTAL_ENTRIES};\n"
        f"pub const TOKEN_RATE_IDENTIFIER_MAX_CODEPOINTS: usize = {identifier_max};\n"
    )


def render_token_rate_typescript_constant(document: dict[str, JsonValue]) -> str:
    maximum = _token_rate_max_entries(document)
    identifier_max = _token_rate_identifier_max_codepoints(document)
    if MAX_TOKEN_RATE_TOTAL_ENTRIES != maximum * 2:
        raise ValueError("Token-rate aggregate limit must cover two per-agent views")
    return (
        f"export const TOKEN_RATE_MAX_ENTRIES = {maximum} as const;\n"
        f"export const TOKEN_RATE_MAX_TOTAL_ENTRIES = {MAX_TOKEN_RATE_TOTAL_ENTRIES} as const;\n"
        f"export const TOKEN_RATE_IDENTIFIER_MAX_CODEPOINTS = {identifier_max} as const;"
    )


def _normalize_recursive_json_value(generated: str) -> str:
    """Break openapi-typescript's indexed self-reference for the recursive JSON schema."""
    start = re.search(r"(?m)^([ \t]*)JsonValue: ", generated)
    if start is None:
        raise ValueError("openapi-typescript output has no unique recursive JsonValue component")
    ending = re.search(
        rf"(?m)^{re.escape(start.group(1))}}}[^;\n]*;",
        generated[start.end() :],
    )
    if ending is None:
        raise ValueError("openapi-typescript output has no unique recursive JsonValue component")
    end = start.end() + ending.end()
    definition = generated[start.start() : end]
    if 'components["schemas"]["JsonValue"]' not in definition:
        raise ValueError("openapi-typescript output has no unique recursive JsonValue component")
    return generated[: start.start()] + start.group(1) + "JsonValue: JsonValue;" + generated[end:]


def render(document: dict[str, JsonValue]) -> str:
    remove_orphan_fastapi_validation_schemas(document)
    normalize_json_value_schema(document)
    bound_integer_schemas(document)
    validate_contract_schemas(document)
    validate_error_responses(document)
    entities = entity_schema_names(document)
    sync_protocol_typescript = render_sync_protocol_typescript(document)
    token_rate_typescript_constant = render_token_rate_typescript_constant(document)
    components = document.get("components")
    schemas = components.get("schemas") if isinstance(components, dict) else None
    include_sync_entity_payload = isinstance(schemas, dict) and "SyncEntityPayload" in schemas
    cache_root = Path(os.environ.get(CACHE_ROOT_ENV, DEFAULT_CACHE_ROOT))
    temp_root = cache_root / OPENAPI_TEMP_DIRECTORY
    temp_root.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="generation-", dir=temp_root) as temp_name:
        temp = Path(temp_name)
        input_path = temp / "openapi.json"
        output_path = temp / "api.ts"
        input_path.write_text(
            json.dumps(document, ensure_ascii=False, separators=(",", ":")) + "\n",
            encoding="utf-8",
        )
        if not GENERATOR_PATH.is_file():
            raise FileNotFoundError("Run `pnpm install --frozen-lockfile` at the repository root to install pinned API tools")
        subprocess.run(
            [
                str(GENERATOR_PATH),
                str(input_path),
                "--output",
                str(output_path),
                "--alphabetize",
                "--default-non-nullable=false",
            ],
            cwd=ROOT,
            check=True,
            text=True,
        )
        generated = output_path.read_text(encoding="utf-8")
    if "export interface components" not in generated and "export type components" not in generated:
        raise ValueError("openapi-typescript output is missing the components export")
    generated = _normalize_recursive_json_value(generated)
    generated += "\n\n" + JSON_VALUE_TS_ALIAS + _entity_aliases(
        entities, include_sync_entity_payload
    ) + "\n"
    if not FORMATTER_PATH.is_file():
        raise FileNotFoundError("Run `pnpm install --frozen-lockfile` at the repository root to install pinned API tools")
    with tempfile.TemporaryDirectory(prefix="format-", dir=temp_root) as temp_name:
        output_path = Path(temp_name) / "api.ts"
        output_path.write_text(generated, encoding="utf-8")
        subprocess.run(
            [
                str(FORMATTER_PATH),
                "--write",
                f"--config={ROOT / '.oxfmtrc.json'}",
                str(output_path),
            ],
            cwd=ROOT,
            check=True,
            text=True,
        )
        return (output_path.read_text(encoding="utf-8")
                + f"\n{sync_protocol_typescript}\n{token_rate_typescript_constant}\n")


def _agent_limit(document: dict[str, JsonValue], model: str, field: str, key: str) -> int:
    components = document.get("components")
    schemas = components.get("schemas") if isinstance(components, dict) else None
    schema = schemas.get(model) if isinstance(schemas, dict) else None
    properties = schema.get("properties") if isinstance(schema, dict) else None
    property_schema = properties.get(field) if isinstance(properties, dict) else None
    value = property_schema.get(key) if isinstance(property_schema, dict) else None
    if isinstance(value, bool) or not isinstance(value, (int, float)) or int(value) != value:
        raise ValueError(f"OpenAPI agent limit {model}.{field}.{key} is not an integer")
    return int(value)


def render_schema_identity(schema_hash: str, document: dict[str, JsonValue]) -> str:
    min_concurrency = _agent_limit(document, "CreateAgentRequest", "concurrency", "minimum")
    default_concurrency = _agent_limit(document, "CreateAgentRequest", "concurrency", "default")
    max_concurrency = _agent_limit(document, "CreateAgentRequest", "concurrency", "maximum")
    min_team_agents = _agent_limit(document, "CreateAgentRequest", "maxAgents", "minimum")
    default_team_agents = _agent_limit(document, "CreateAgentRequest", "maxAgents", "default")
    max_team_agents = _agent_limit(document, "CreateAgentRequest", "maxAgents", "maximum")
    return (
        "export const API_SCHEMA_HASH =\n"
        f'  "{schema_hash}";\n'
        f'export const API_SCHEMA_HASH_HEADER = "{API_SCHEMA_HASH_HEADER}";\n'
        f'export const API_SCHEMA_HASH_PARAM = "{API_SCHEMA_HASH_PARAM}";\n'
        f'export const API_SCHEMA_MISMATCH_HEADER = "{API_SCHEMA_MISMATCH_HEADER}";\n'
        f'export const API_SCHEMA_MISMATCH_FIELD = "{API_SCHEMA_MISMATCH_FIELD}";\n'
        f"export const MIN_SUBAGENT_CONCURRENCY = {min_concurrency};\n"
        f"export const DEFAULT_SUBAGENT_CONCURRENCY = {default_concurrency};\n"
        f"export const MAX_SUBAGENT_CONCURRENCY = {max_concurrency};\n"
        f"export const MIN_TEAM_AGENTS = {min_team_agents};\n"
        f"export const DEFAULT_MAX_TEAM_AGENTS = {default_team_agents};\n"
        f"export const MAX_TEAM_AGENTS = {max_team_agents};\n"
    )


def export_openapi_source(document: dict[str, JsonValue]) -> bytes:
    """Keep the committed authority readable; the hash canonicalizes separately."""
    return (json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode("utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated API types are stale")
    parser.add_argument(
        "--write-openapi",
        action="store_true",
        help="refresh the canonical OpenAPI authority from the current Python models",
    )
    options = parser.parse_args(argv)
    try:
        exported = openapi_document()
        exported_source = export_openapi_source(exported)
        if options.write_openapi:
            OPENAPI_AUTHORITY.write_bytes(exported_source)
        else:
            committed = OPENAPI_AUTHORITY.read_bytes()
            if committed != exported_source:
                print(
                    f"{OPENAPI_AUTHORITY.relative_to(ROOT)} diverges from Python models; "
                    "review the schema change, then run `pnpm run api:generate`",
                    file=sys.stderr,
                )
                return 1
        document = json.loads(OPENAPI_AUTHORITY.read_text(encoding="utf-8"))
        schema_hash = api_schema_hash(document)
        expected_files = {
            OUTPUT: render(document),
            SCHEMA_OUTPUT: render_schema_identity(schema_hash, document),
            SYNC_PROTOCOL_OUTPUT: render_sync_protocol_rust(document),
            SYNC_PROTOCOL_PYTHON_OUTPUT: render_sync_protocol_python(document),
            SYNC_PROTOCOL_NODE_OUTPUT: render_sync_protocol_node(document),
            TOKEN_RATE_LIMITS_OUTPUT: render_token_rate_limits(document),
        }
    except (FileNotFoundError, RuntimeError, ValueError, subprocess.CalledProcessError) as error:
        print(f"API type generation failed: {error}", file=sys.stderr)
        return 1
    for path, expected in expected_files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if options.check:
            if current != expected:
                print(f"{path.relative_to(ROOT)} is stale; run `pnpm --workspace-root run api:generate`", file=sys.stderr)
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    subprocess.run(
        ["cargo", "check", "--locked", "--package", "studio-runtime-http"],
        cwd=ROOT,
        check=True,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
