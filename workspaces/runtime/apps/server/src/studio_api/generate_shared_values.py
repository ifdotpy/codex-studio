def rust_str(name: str, value: str) -> str:
    """Write a Rust string constant in rustfmt's layout (100 columns)."""
    line = f"pub const {name}: &str = {json.dumps(value)};"
    tail = f"    {json.dumps(value)};"
    if len(line) <= 100 or len(tail) > 100:
        return line + "\n"
    return f"pub const {name}: &str =\n{tail}\n"


