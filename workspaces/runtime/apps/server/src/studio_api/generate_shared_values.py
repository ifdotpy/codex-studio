def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write generated shared values")
    mode.add_argument("--check", action="store_true", help="fail when generated values are stale")
    args = parser.parse_args(argv)
    for path, expected in OUTPUTS.items():
        try:
            current = path.read_text(encoding="utf-8")
        except (OSError, UnicodeError):
            current = None
        if args.check:
            if current != expected:
                print(f"{path.relative_to(REPOSITORY_ROOT)} is stale; run `pnpm run shared-values:generate`", file=sys.stderr)
                return 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
