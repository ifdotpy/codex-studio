use crate::TestJson;
use serde_json::{Value, json};
use studio_runtime_services::rules_engine::{
    CheckResult, RuleDecision, TickObservation, active_workers,
};

fn oracle() -> Vec<Value> {
    serde_json::from_str(include_str!("rules_engine/expected.json"))
        .expect("frozen rules decisions")
}

fn monitor_record(value: &Value) -> studio_runtime_store::MonitorRecord {
    let mut complete = json!({"id":"monitor","agent":"owner","epoch":0,"status":"running","requestId":"request","created":0,"activityAt":0,"activityGeneration":0,"bytes":0,"command":"","cwd":std::env::temp_dir(),"interactive":false,"livenessCommand":"","log":std::env::temp_dir().join("watch.log"),"stallTimeoutSeconds":1800,"stallWakeGeneration":-1,"successExitCodes":[0],"tail":"","timeout_ms":3600000,"wakeOn":"exit"});
    complete.as_object_mut().expect("valid fixture").extend(value.as_object().expect("valid fixture").clone());
    serde_json::from_value(complete).expect("valid fixture")
}
fn rule_record(value: &Value) -> studio_runtime_store::RuleRecord { serde_json::from_value(value.clone()).expect("valid fixture") }

#[test]
fn python_written_records_and_real_rules_functions_match() {
    let corpus = oracle();
    for case in &corpus {
        let name = case["name"].as_str().expect("case name");
        let mut migrated = case["rule"].clone();
        for (field, value) in [("checks", json!(0)), ("wakes", json!(0)), ("inFlight", json!(false)), ("fileGeneration", json!(0)), ("stallTimeoutSeconds", json!(1800)), ("stallWakeGeneration", json!(-1)), ("livenessCommand", json!("")), ("event", json!(""))] {
            migrated.as_object_mut().expect("valid fixture").entry(field).or_insert(value);
        }
        let snapshot = crate::rule_snapshot(migrated, case["owner"].clone())
            .unwrap_or_else(|error| panic!("{name}: constructor: {error}"));
        let now = case["now"].as_f64().expect("clock");
        let decision = match case["operation"].as_str().expect("operation") {
            "tick" => {
                let fingerprint = snapshot.fingerprint_path(now).map(|_| {
                    serde_json::from_value(case["fingerprint"].clone()).expect("fingerprint")
                });
                let mut agents = case["workers"].as_array().expect("workers").clone();
                agents.push(case["owner"].clone());
                let activity =
                    active_workers(&agents, &case["monitors"].as_array().expect("monitors").iter().map(monitor_record).collect::<Vec<_>>())
                        .expect("activity checked");
                snapshot.tick(
                    now,
                    TickObservation {
                        fingerprint,
                        active_workers: Some(activity),
                        held_input: false,
                    },
                )
            }
            "finish" => snapshot.finish(
                now,
                CheckResult {
                    code: case["result"]["code"].as_i64(),
                    error: case["result"]["error"].as_str(),
                    cancelled: false,
                    output: case["result"]["output"].as_str().expect("output"),
                },
            ),
            "recover" => snapshot.recover(now),
            "event" => snapshot.event(
                case["event"]["kind"].as_str().expect("kind"),
                case["event"]["text"].as_str().expect("text"),
                case["event"]["key"].as_str().expect("key"),
                now,
            ),
            operation => panic!("unexpected operation {operation}"),
        }
        .unwrap_or_else(|error| panic!("{name}: decision: {error}"));
        assert_eq!(
            normalize(actual(case, &decision)),
            normalize(case["expected"].clone()),
            "complete decision differs for {name}"
        );
    }
    assert!(corpus.len() >= 100);
}

fn actual(case: &Value, decision: &RuleDecision) -> Value {
    let rule = decision.record.as_ref().map(|r| r.value()).unwrap_or_else(|| case["rule"].clone());
    let wakes = decision
        .wake
        .iter()
        .map(|wake| json!({"id":wake.id,"kind":wake.kind,"text":wake.text}))
        .collect::<Vec<_>>();
    let launches = decision.check.iter().map(|check|json!({
        "agent":check.agent_id,"data":{"command":check.command,"timeout_ms":check.timeout_ms,"stall_timeout_seconds":0},
        "key":format!("rule:{}:{}",check.rule_id,check.check_number),"approved":true,"epoch":check.epoch,"rule":rule
    })).collect::<Vec<_>>();
    json!({"rule":rule,"wakes":wakes,"launches":launches})
}

// Only JSON text generated by RulesMixin itself is decoded. Arbitrary command output
// and event text retain their exact Unicode, whitespace, order and truncation semantics.
fn normalize(mut value: Value) -> Value {
    fn strip_record_nulls(record: &mut Value) {
        if let Some(fields) = record.as_object_mut() { fields.retain(|_, value| !value.is_null()); }
    }
    strip_record_nulls(&mut value["rule"]);
    if let Some(launches) = value["launches"].as_array_mut() {
        for launch in launches { strip_record_nulls(&mut launch["rule"]); }
    }
    if let Some(text) = value["rule"]["stallText"].as_str() {
        value["rule"]["stallText"] = serde_json::from_str(text).expect("generated stall payload");
    }
    let low_workers = value["rule"]["kind"] == "low_workers";
    if low_workers && let Some(output) = value["rule"]["lastOutput"].as_str() {
        value["rule"]["lastOutput"] =
            serde_json::from_str(output).expect("generated worker output");
    }
    for wake in value["wakes"].as_array_mut().expect("wakes") {
        let mut text: Value = serde_json::from_str(wake["text"].as_str().expect("wake text"))
            .expect("generated wake payload");
        if low_workers && let Some(output) = text["output"].as_str() {
            text["output"] = serde_json::from_str(output).expect("generated worker wake");
        }
        wake["text"] = text;
    }
    for launch in value["launches"].as_array_mut().expect("launches") {
        if let Some(text) = launch["rule"]["stallText"].as_str() {
            launch["rule"]["stallText"] =
                serde_json::from_str(text).expect("generated stall payload");
        }
    }
    value
}

#[test]
fn malformed_stored_fields_are_located_and_never_panic() {
    let corpus = oracle();
    let base = &corpus[0];
    for (field, invalid) in [
        ("checks", json!(-1)),
        ("checks", json!(true)),
        ("checks", json!(9_007_199_254_740_992_u64)),
        ("intervalSeconds", json!(0)),
        ("inFlight", json!("false")),
        ("kind", json!("alien")),
        ("fileGeneration", json!(-1)),
        ("stallWakeGeneration", json!(-2)),
        ("fingerprint", json!([1, 2])),
        ("name", json!("x".repeat(121))),
    ] {
        let mut rule = base["rule"].clone();
        rule[field] = invalid;
        let error = crate::rule_snapshot(rule, base["owner"].clone())
            .err()
            .expect("malformed record refused");
        assert!(
            field == "kind" || error.to_string().contains(&format!("/{field}")),
            "{field}: {error}"
        );
    }
    for field in [
        "id",
        "agent",
        "epoch",
        "name",
        "status",
        "kind",
        "intervalSeconds",
        "nextAt",
        "created",
        "command",
        "text",
    ] {
        let mut rule = base["rule"].clone();
        rule.as_object_mut().expect("rule").remove(field);
        assert!(
            crate::rule_snapshot(rule, base["owner"].clone()).is_err(),
            "missing {field}"
        );
    }
}

#[test]
fn sampled_configuration_and_exact_completion_identity_are_checked() {
    let corpus = oracle();
    let find = |name| {
        corpus
            .iter()
            .find(|case| case["name"] == name)
            .expect("named oracle witness")
    };
    let due = find("interval-boundary-0");
    let snapshot = crate::rule_snapshot(due["rule"].clone(), due["owner"].clone())
        .expect("checked Python record");
    assert!(snapshot.current(&rule_record(&due["rule"]), &due["owner"]));
    let mut unrelated_path = due["rule"].clone();
    unrelated_path["path"] = json!("/disposable/unused");
    let interval =
        crate::rule_snapshot(unrelated_path, due["owner"].clone()).expect("open record");
    assert_eq!(
        interval.fingerprint_path(due["now"].as_f64().expect("clock")),
        None
    );
    assert!(!snapshot.current(&rule_record(&find("interval-boundary-1")["rule"]), &due["owner"]));
    for name in [
        "interval-stopped-autoWake",
        "interval-stopped-epoch",
        "interval-stopped-deletedAt",
    ] {
        assert!(
            !snapshot.current(&rule_record(&due["rule"]), &find(name)["owner"]),
            "stale owner {name}"
        );
    }
    let decision = snapshot
        .tick(
            due["now"].as_f64().expect("now"),
            TickObservation::default(),
        )
        .expect("reserve");
    let check = decision.check.expect("command check");
    let active = decision.record.expect("in-flight record");
    let snapshot = crate::rule_snapshot(active.value(), due["owner"].clone())
        .expect("checked reservation");
    let mut foreign = check.clone();
    foreign.monitor_id = "foreign".to_owned();
    assert!(
        snapshot
            .finish_check(
                &foreign,
                CheckResult {
                    code: Some(0),
                    error: None,
                    cancelled: false,
                    output: "must not wake"
                },
                0.0
            )
            .expect("foreign refusal")
            .record
            .is_none()
    );
    let stopped =
        crate::rule_snapshot(active.value(), find("interval-stopped-epoch")["owner"].clone())
            .expect("new owner epoch");
    assert!(
        stopped
            .finish_check(
                &check,
                CheckResult {
                    code: Some(0),
                    error: None,
                    cancelled: false,
                    output: "stale"
                },
                0.0
            )
            .expect("stale refusal")
            .record
            .is_none()
    );
    let finished = snapshot
        .finish_check(
            &check,
            CheckResult {
                code: Some(0),
                error: None,
                cancelled: false,
                output: "ok",
            },
            0.0,
        )
        .expect("finish");
    let snapshot =
        crate::rule_snapshot(finished.record.expect("finished").value(), due["owner"].clone())
            .expect("checked finished record");
    assert!(
        snapshot
            .finish_check(
                &check,
                CheckResult {
                    code: Some(0),
                    error: None,
                    cancelled: false,
                    output: "duplicate"
                },
                0.0
            )
            .expect("repeat refusal")
            .record
            .is_none()
    );
}
