TOKENS = {}
ORIGINAL_DIGEST = efficiency.digest

def digest(value):
    token = ORIGINAL_DIGEST(value)
    canonical = json.dumps(value, ensure_ascii=False, separators=(",", ":"), sort_keys=True)
    TOKENS[token] = hashlib.sha256(canonical.encode()).hexdigest()[:24]
    return token


def convert_tokens(value):
    if isinstance(value, dict):
        return {k: convert_tokens(v) for k, v in value.items()}
    if isinstance(value, list):
        return [convert_tokens(v) for v in value]
    if isinstance(value, str):
        return TOKENS.get(value, value)
    return value


def normalized(value):
    if isinstance(value, dict):
        return {k: normalized(v) for k, v in value.items()}
    if isinstance(value, list):
        return [normalized(v) for v in value]
    if isinstance(value, str):
        for token in {*TOKENS, *TOKENS.values()}:
            value = value.replace(token, "<version>")
        # JSON objects are consumed structurally; whitespace/key order is immaterial.
        try:
            return {"json": normalized(json.loads(value))} if value.startswith(("{", "[")) else value
        except (ValueError, TypeError):
            # Only complete JSON blocks in provider text, never user/transcript input.
            return value
    return value


def normalize_text(text):
    for token in {*TOKENS, *TOKENS.values()}:
        text = text.replace(token, "<version>")
    # Compact only complete object lines generated by the compiler.
    lines = []
    for line in text.split("\n"):
        if line.startswith("{"):
            try:
                line = json.dumps(json.loads(line), ensure_ascii=False, sort_keys=True, separators=(",", ":"))
            except ValueError:
                pass
        lines.append(line)
    return "\n".join(lines)


def normalize_output(value):
    value = copy.deepcopy(value)
    for key in ("manifest", "metadata_patches", "delivery"):
        if key in value:
            value[key] = normalized(value[key])
    if value.get("ok"):
        for item in value["provider_inputs"]:
            if item["type"] == "text": item["text"] = normalize_text(item["text"])
        # Parent transcript is a view of the exact model text, with its own budget.
        if value.get("fulltext") is not None:
            assert value["transcript"]["text"] == value["fulltext"][:20000], "parent excerpt differs from fulltext"
            assert value["transcript"]["truncated"] and len(value["fulltext"]) > 20000
            value["fulltext"] = normalize_text(value["fulltext"])
            value["transcript"]["text"] = value["fulltext"][:20000]
        else:
            assert not value["transcript"]["truncated"]
            value["transcript"]["text"] = normalize_text(value["transcript"]["text"])
    return value


def merge(target, patch):
    for key, value in patch.items():
        if isinstance(value, dict) and isinstance(target.get(key), dict): merge(target[key], value)
        else: target[key] = copy.deepcopy(value)
    return target


