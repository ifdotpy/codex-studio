fn check_delivery_parity(openapi: &Value) -> Result<(), String> {
    let canonical = DeliveryMoment::ALL.map(DeliveryMoment::as_str);
    let input: Vec<_> = canonical
        .into_iter()
        .chain(delivery::LEGACY_DELIVERY_MOMENTS.map(|(name, _)| name))
        .collect();
    for (name, expected) in [
        ("DeliveryMoment", serde_json::json!(canonical)),
        ("DeliveryMomentInput", serde_json::json!(input)),
    ] {
        let path = format!("/components/schemas/{name}/enum");
        if openapi.pointer(&path) != Some(&expected) {
            return Err(format!("{path} must match runtime-schema/src/delivery.rs"));
        }
    }
    let schemas = openapi
        .pointer("/components/schemas")
        .and_then(Value::as_object)
        .ok_or("missing schemas")?;
    for (name, schema) in schemas {
        for field in ["delivery", "requestedDelivery"] {
            let Some(property) = schema.pointer(&format!("/properties/{field}")) else {
                continue;
            };
            // Terminal input delivery is an unrelated status contract.
            if name == "TerminalInputResult" {
                continue;
            }
            let reference = if name == "ManagedMessageBody" {
                "#/components/schemas/DeliveryMomentInput"
            } else {
                "#/components/schemas/DeliveryMoment"
            };
            let variants: Vec<_> = property
                .get("anyOf")
                .and_then(Value::as_array)
                .map(|items| {
                    items
                        .iter()
                        .filter(|item| item.get("type").and_then(Value::as_str) != Some("null"))
                        .collect()
                })
                .unwrap_or_else(|| vec![property]);
            if variants
                .iter()
                .any(|item| item.get("$ref").and_then(Value::as_str) != Some(reference))
            {
                return Err(format!(
                    "{name}.{field} must reference {reference}, owned by runtime-schema/src/delivery.rs"
                ));
            }
            if let Some(default) = property.get("default").filter(|value| !value.is_null())
                && default.as_str() != Some(DeliveryMoment::default().as_str())
            {
                return Err(format!(
                    "{name}.{field} default must match DeliveryMoment::default()"
                ));
            }
        }
    }
    Ok(())
}

