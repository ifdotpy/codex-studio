fn json_string(value: &str) -> String {
    serde_json::to_string(value).expect("a string serializes")
}

fn ts_constants(lines: &mut String, constants: &[(&str, String)]) {
    for (name, value) in constants {
        writeln!(lines, "export const {name} = {value};").expect("writing to a String");
    }
}

fn ts_strings(lines: &mut String, constants: &[(&str, &str)]) {
    for (name, value) in constants {
        writeln!(lines, "export const {name} =\n  {};", json_string(value))
            .expect("writing to a String");
    }
}

