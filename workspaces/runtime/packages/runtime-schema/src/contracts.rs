fn delivery_moment_ts() -> String {
    let mut text = format!("// {HEADER}\nexport const DeliveryMoment = {{\n");
    for moment in DeliveryMoment::ALL {
        writeln!(text, "  {moment:?}: {},", json_string(moment.as_str())).expect("write string");
    }
    text.push_str("} as const;\nexport type DeliveryMoment =\n  (typeof DeliveryMoment)[keyof typeof DeliveryMoment];\n");
    text.push_str("\nexport function normalizeDelivery(value: unknown): DeliveryMoment {\n  switch (value) {\n");
    for moment in DeliveryMoment::ALL {
        writeln!(text, "    case DeliveryMoment.{moment:?}:").expect("write string");
    }
    text.push_str("      return value;\n");
    for (legacy, moment) in delivery::LEGACY_DELIVERY_MOMENTS {
        writeln!(
            text,
            "    case {}:\n      return DeliveryMoment.{moment:?};",
            json_string(legacy)
        )
        .expect("write string");
    }
    text.push_str("    default:\n      throw new Error(\"Invalid delivery moment\");\n  }\n}\n");
    text
}

