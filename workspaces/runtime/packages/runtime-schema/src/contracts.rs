fn read_json(root: &Path, path: &str) -> Result<Value, String> {
    let text =
        std::fs::read_to_string(root.join(path)).map_err(|error| format!("{path}: {error}"))?;
    serde_json::from_str(&text).map_err(|error| format!("{path}: {error}"))
}

fn expect_number(document: &Value, pointer: &str, expected: i64) -> Result<(), String> {
    match document.pointer(pointer).and_then(Value::as_f64) {
        Some(actual) if actual == expected as f64 => Ok(()),
        actual => Err(format!(
            "{pointer} is {actual:?}; the Rust owner requires {expected}"
        )),
    }
}

/// Hold the committed OpenAPI document and persisted-state schemas to the Rust owners.
pub fn check_schema_parity(openapi: &Value, account_transfer: &Value) -> Result<(), String> {
    let concurrency = [
        agent_limits::MIN_SUBAGENT_CONCURRENCY,
        agent_limits::DEFAULT_SUBAGENT_CONCURRENCY,
        agent_limits::MAX_SUBAGENT_CONCURRENCY,
    ];
    let team = [
        agent_limits::MIN_TEAM_AGENTS,
        agent_limits::DEFAULT_MAX_TEAM_AGENTS,
        agent_limits::MAX_TEAM_AGENTS as i64,
    ];
    for (field, limits) in [
        ("CreateAgentRequest/properties/concurrency", concurrency),
        ("CreateAgentRequest/properties/maxAgents", team),
        ("ConfigureRequest/properties/concurrency", concurrency),
        ("ConfigureRequest/properties/maxAgents", team),
        (
            "ConversationRequest/properties/subagent_concurrency",
            concurrency,
        ),
    ] {
        for (key, expected) in ["minimum", "default", "maximum"].into_iter().zip(limits) {
            expect_number(
                openapi,
                &format!("/components/schemas/{field}/{key}"),
                expected,
            )?;
        }
    }
    let version = i64::from(crate::SYNC_PROTOCOL_VERSION);
    let protocol = "/components/schemas/SyncProtocolResponse/properties";
    expect_number(
        openapi,
        &format!("{protocol}/protocolVersion/const"),
        version,
    )?;
    expect_number(
        openapi,
        &format!("{protocol}/supportedVersions/items/const"),
        version,
    )?;
    let snapshot = "/components/schemas/TokenRateSnapshot/properties";
    let entries = crate::TOKEN_RATE_MAX_ENTRIES as i64;
    let identifier = crate::TOKEN_RATE_IDENTIFIER_MAX_CODEPOINTS as i64;
    for map in ["/rates", "/teams", "/teams/additionalProperties"] {
        expect_number(openapi, &format!("{snapshot}{map}/maxProperties"), entries)?;
        expect_number(
            openapi,
            &format!("{snapshot}{map}/propertyNames/minLength"),
            1,
        )?;
        expect_number(
            openapi,
            &format!("{snapshot}{map}/propertyNames/maxLength"),
            identifier,
        )?;
    }
    let turn_id = "/components/schemas/TokenRateValue/properties/turnId";
    expect_number(openapi, &format!("{turn_id}/minLength"), 1)?;
    expect_number(openapi, &format!("{turn_id}/maxLength"), identifier)?;
    expect_number(
        account_transfer,
        "/properties/members/maxProperties",
        agent_limits::MAX_TRANSFER_AGENT_RECORDS as i64,
    )
}

fn api_types(root: &Path) -> Result<String, String> {
    let node = std::env::var(NODE_ENVIRONMENT).unwrap_or_else(|_| "node".into());
    let output = Command::new(&node)
        .arg(root.join(API_TYPES_SCRIPT))
        .arg(root.join(OPENAPI_PATH))
        .current_dir(root)
        .output()
        .map_err(|error| format!("cannot start {node}: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "{API_TYPES_SCRIPT} failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let body = String::from_utf8(output.stdout)
        .map_err(|error| format!("{API_TYPES_SCRIPT} printed invalid UTF-8: {error}"))?;
    Ok(body + &api_types_tail())
}

/// Render every contract file. `with_api_types` also runs Node for `api.ts`.
pub fn render(root: &Path, with_api_types: bool) -> Result<Vec<Rendered>, String> {
    let openapi = read_json(root, OPENAPI_PATH)?;
    check_schema_parity(&openapi, &read_json(root, ACCOUNT_TRANSFER_SCHEMA_PATH)?)?;
    let web = |name: &str| format!("{WEB_GENERATED}/{name}");
    let mut rendered = vec![
        Rendered {
            path: web("sharedValues.ts"),
            text: shared_values_ts(),
        },
        Rendered {
            path: web("multiServerProtocol.ts"),
            text: multi_server_protocol_ts(),
        },
        Rendered {
            path: web("apiSchema.ts"),
            text: api_schema_ts(&api_schema::schema_hash(&openapi)),
        },
        Rendered {
            path: "workspaces/runtime/apps/vm-guest/shared_values_generated.py".into(),
            text: vm_guest_py(),
        },
        Rendered {
            path: "workspaces/client/apps/desktop/native/linux-vm/shared_values_generated.swift"
                .into(),
            text: linux_vm_swift(),
        },
    ];
    if with_api_types {
        rendered.push(Rendered {
            path: web("api.ts"),
            text: api_types(root)?,
        });
    }
    Ok(rendered)
}

/// Repository-relative paths whose committed text differs from `rendered`.
pub fn stale(root: &Path, rendered: &[Rendered]) -> Vec<String> {
    rendered
        .iter()
        .filter(|file| {
            std::fs::read_to_string(root.join(&file.path))
                .ok()
                .as_deref()
                != Some(file.text.as_str())
        })
        .map(|file| file.path.clone())
        .collect()
}

/// The repository root of this source tree.
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../..")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn committed_contract_copies_match_the_rust_owners() {
        let root = repository_root();
        let rendered = render(&root, false).expect("contracts render");
        assert_eq!(
            stale(&root, &rendered),
            Vec::<String>::new(),
            "run `pnpm run contracts:generate`"
        );
    }

    #[test]
    fn schema_parity_rejects_a_limit_that_leaves_its_rust_owner() {
        let root = repository_root();
        let account_transfer =
            read_json(&root, ACCOUNT_TRANSFER_SCHEMA_PATH).expect("account transfer schema");
        let mut openapi = read_json(&root, OPENAPI_PATH).expect("OpenAPI document");
        check_schema_parity(&openapi, &account_transfer).expect("committed schemas agree");
        *openapi
            .pointer_mut("/components/schemas/CreateAgentRequest/properties/maxAgents/maximum")
            .expect("team limit is present") = serde_json::json!(1);
        let error = check_schema_parity(&openapi, &account_transfer)
            .expect_err("a changed team limit is rejected");
        assert!(error.contains("maxAgents/maximum"), "{error}");
    }
}
