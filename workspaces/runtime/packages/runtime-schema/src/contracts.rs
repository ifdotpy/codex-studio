fn api_types(root: &Path, document: &Value, argument: &str) -> Result<String, String> {
    let node = std::env::var(NODE_ENVIRONMENT).unwrap_or_else(|_| "node".into());
    let mut child = Command::new(&node)
        .arg(root.join(API_TYPES_SCRIPT))
        .arg(argument)
        .current_dir(root)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|error| format!("cannot start {node}: {error}"))?;
    child
        .stdin
        .take()
        .ok_or("missing schema input")?
        .write_all(document.to_string().as_bytes())
        .map_err(|error| error.to_string())?;
    let output = child
        .wait_with_output()
        .map_err(|error| error.to_string())?;
    if !output.status.success() {
        return Err(format!(
            "{API_TYPES_SCRIPT} failed: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    let body = String::from_utf8(output.stdout)
        .map_err(|error| format!("{API_TYPES_SCRIPT} printed invalid UTF-8: {error}"))?;
    Ok(body)
}

/// Render every contract file. `with_api_types` also runs Node for web types.
pub fn render(root: &Path, with_api_types: bool) -> Result<Vec<Rendered>, String> {
    let mut openapi = read_json(root, OPENAPI_PATH)?;
    for (name, schema) in crate::agent_progress::schemas()
        .into_iter()
        .chain(crate::desktop::schemas())
    {
        *openapi
            .pointer_mut(&format!("/components/schemas/{name}"))
            .ok_or_else(|| format!("OpenAPI is missing Rust-owned {name}"))? = schema;
    }
    check_schema_parity(&openapi, &read_json(root, ACCOUNT_TRANSFER_SCHEMA_PATH)?)?;
    for (name, fields) in [
        (
            "runtime-event-metadata",
            &["delivery", "requestedDelivery"][..],
        ),
        ("federation-chat-payload", &["delivery"][..]),
    ] {
        let path =
            format!("workspaces/runtime/packages/runtime-schema/src/schemas/{name}.schema.json");
        let schema = read_json(root, &path)?;
        for field in fields {
            let expected = serde_json::json!({"anyOf":[
                {"$ref":format!("{}#/components/schemas/DeliveryMomentInput", crate::OPENAPI_URI)},
                {"type":"null"}
            ]});
            if schema.pointer(&format!("/properties/{field}")) != Some(&expected) {
                return Err(format!(
                    "{path}.{field} must reference DeliveryMomentInput, owned by runtime-schema/src/delivery.rs"
                ));
            }
        }
    }
    let web = |name: &str| format!("{WEB_GENERATED}/{name}");
    let mut rendered = vec![
        Rendered {
            path: web("taskReview.ts"),
            text: format!(
                "// {HEADER}\nexport const DEFAULT_GATE_TIMEOUT_MS = {};\nexport const MAX_GATE_TIMEOUT_MS = {};\nexport const MAX_RESULT_SCHEMA_BYTES = {};\n",
                crate::task_gate::DEFAULT_TIMEOUT_MS,
                crate::task_gate::MAX_TIMEOUT_MS,
                crate::task_results::MAX_RESULT_SCHEMA_BYTES
            ),
        },
        Rendered {
            path: web("claudePermissions.ts"),
            text: format!(
                "// {HEADER}\nexport const CLAUDE_PERMISSION_MODES = [\n{}] as const;\nexport type ClaudePermissionMode = (typeof CLAUDE_PERMISSION_MODES)[number];\n",
                crate::claude_permissions::PERMISSION_MODES
                    .iter()
                    .map(|mode| format!("  {},\n", json_string(mode)))
                    .collect::<String>()
            ),
        },
        Rendered {
            path: "workspaces/providers/apps/claude-bridge/input-origin.generated.mjs".into(),
            text: format!(
                "// {HEADER}\nexport const HUMAN_INPUT = {};\nexport const STUDIO_EVENT_INPUT = {};\n",
                json_string(crate::provider_input::ProviderInputOrigin::Human.as_str()),
                json_string(crate::provider_input::ProviderInputOrigin::StudioEvent.as_str()),
            ),
        },
        Rendered {
            path: OPENAPI_PATH.into(),
            text: serde_json::to_string_pretty(&openapi).map_err(|error| error.to_string())? + "\n",
        },
        Rendered {
            path: web("deliveryMoment.ts"),
            text: delivery_moment_ts(),
        },
        Rendered {
            path: web("sharedValues.ts"),
            text: shared_values_ts(),
        },
        Rendered {
            path: web("multiServerProtocol.ts"),
            text: multi_server_protocol_ts(),
        },
        Rendered {
            path: web("apiSchema.ts"),
            text: api_schema_ts(&api_schema::schema_hash(&openapi)),
        },
        Rendered {
            path: "workspaces/runtime/apps/vm-guest/shared_values_generated.py".into(),
            text: vm_guest_py(),
        },
        Rendered {
            path: "workspaces/client/apps/desktop/native/linux-vm/shared_values_generated.swift"
                .into(),
            text: linux_vm_swift(),
        },
    ];
    let draft_schema = studio_client_domain::drafts::schema().to_value();
    rendered.push(Rendered {
        path: "workspaces/runtime/packages/runtime-http/draft-payload.schema.json".into(),
        text: serde_json::to_string_pretty(&draft_schema).map_err(|error| error.to_string())?
            + "\n",
    });
    if with_api_types {
        let mut generator = schemars::generate::SchemaSettings::draft2020_12()
            .for_serialize()
            .with(|settings| settings.definitions_path = "/components/schemas".into())
            .into_generator();
        generator.subschema_for::<studio_client_domain::drafts::DraftVersion>();
        generator.subschema_for::<studio_client_domain::markdown::MarkdownBlock>();
        let document = serde_json::json!({
            "openapi":"3.1.0", "info":{"title":"Rust-owned contracts","version":"1"},
            "paths":{}, "components":{"schemas":generator.take_definitions(true)}
        });
        rendered.push(Rendered {
            path: web("rustOwned.ts"),
            text: api_types(root, &document, "--rust-owned")?,
        });
        rendered.push(Rendered {
            path: web("api.ts"),
            text: api_types(root, &openapi, "-")? + &api_types_tail(),
        });
    }
    Ok(rendered)
}

/// Repository-relative paths whose committed text differs from `rendered`.
pub fn stale(root: &Path, rendered: &[Rendered]) -> Vec<String> {
    rendered
        .iter()
        .filter(|file| {
            std::fs::read_to_string(root.join(&file.path))
                .ok()
                .as_deref()
                != Some(file.text.as_str())
        })
        .map(|file| file.path.clone())
        .collect()
}

/// The repository root of this source tree.
pub fn repository_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../..")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn markdown_output_matches_rust_owned_schema() {
        use studio_client_domain::{markdown::MarkdownBlock, protocol::Request};
        let schema = schemars::generate::SchemaSettings::draft2020_12()
            .for_serialize()
            .into_generator()
            .into_root_schema_for::<Vec<MarkdownBlock>>();
        let validator =
            jsonschema::validator_for(schema.as_value()).expect("Markdown schema compiles");
        for text in [
            "# Hello 🦀. Next **sentence**.",
            "```html\n<b>inert</b>\n```",
            "```mermaid\ngraph TD; A-->B\n```",
        ] {
            let response = studio_client_domain::markdown::dispatch(&Request {
                id: "markdown-contract".into(),
                method: "markdown.parse".into(),
                params: serde_json::json!({"text":text,"streaming":false}),
            });
            assert!(response.error.is_none());
            assert!(validator.is_valid(&response.result.expect("serialized native output")));
        }
        assert!(!validator.is_valid(&serde_json::json!([{"kind":"script","source":"run()"}])));
        assert!(!validator.is_valid(
            &serde_json::json!([{"nodes":[{"sentences":[{"text":"x","index":"bad"}]}],"length":1}])
        ));
    }

    #[test]
    fn committed_contract_copies_match_the_rust_owners() {
        let root = repository_root();
        let rendered = render(&root, false).expect("contracts render");
        assert!(
            rendered
                .iter()
                .all(|file| !file.path.starts_with("workspaces/runtime/apps/server/"))
        );
        assert!(
            rendered
                .iter()
                .any(|file| file.path
                    == "workspaces/runtime/apps/vm-guest/shared_values_generated.py")
        );
        assert_eq!(
            stale(&root, &rendered),
            Vec::<String>::new(),
            "run `pnpm run contracts:generate`"
        );
    }

    #[test]
    fn schema_parity_rejects_a_limit_that_leaves_its_rust_owner() {
        let root = repository_root();
        let account_transfer =
            read_json(&root, ACCOUNT_TRANSFER_SCHEMA_PATH).expect("account transfer schema");
        let mut openapi = read_json(&root, OPENAPI_PATH).expect("OpenAPI document");
        check_schema_parity(&openapi, &account_transfer).expect("committed schemas agree");
        *openapi
            .pointer_mut("/components/schemas/CreateAgentRequest/properties/maxAgents/maximum")
            .expect("team limit is present") = serde_json::json!(1);
        let error = check_schema_parity(&openapi, &account_transfer)
            .expect_err("a changed team limit is rejected");
        assert!(error.contains("maxAgents/maximum"), "{error}");
    }

    #[test]
    fn claude_permission_parity_rejects_drift_in_each_consumer() {
        let root = repository_root();
        let openapi = read_json(&root, OPENAPI_PATH).expect("OpenAPI document");
        let account_transfer =
            read_json(&root, ACCOUNT_TRANSFER_SCHEMA_PATH).expect("account transfer schema");
        for path in [
            "/components/schemas/CreateAgentRequest/properties/permission_mode/enum",
            "/components/schemas/AgentEntityDto/properties/claudeOptions/anyOf/0/properties/permissionMode/enum",
            "/components/schemas/ClaudeSettings/properties/permissionMode/anyOf/0/enum",
            "/components/schemas/ClaudeSessionSettings/properties/permissionMode/anyOf/0/enum",
        ] {
            let mut drifted = openapi.clone();
            *drifted.pointer_mut(path).expect("permission modes") = serde_json::json!(["unknown"]);
            let error =
                check_schema_parity(&drifted, &account_transfer).expect_err("drift must fail");
            assert!(error.contains(path), "{error}");
            assert!(
                error.contains("claude_permissions::PERMISSION_MODES"),
                "{error}"
            );
        }
    }

    #[test]
    fn delivery_schema_parity_rejects_new_spellings_and_unshared_consumers() {
        let root = repository_root();
        let openapi = read_json(&root, OPENAPI_PATH).expect("OpenAPI document");
        check_delivery_parity(&openapi).expect("delivery contract agrees");
        for path in [
            "/components/schemas/DeliveryMoment/enum",
            "/components/schemas/DeliveryMomentInput/enum",
            "/components/schemas/QueueItem/properties/delivery/$ref",
            "/components/schemas/TranscriptInput/properties/requestedDelivery/anyOf/0/$ref",
            "/components/schemas/ManagedMessageBody/properties/delivery/default",
        ] {
            let mut drifted = openapi.clone();
            *drifted.pointer_mut(path).expect("contract field") = serde_json::json!("drift");
            let error = check_delivery_parity(&drifted).expect_err("drift must fail");
            assert!(
                error.contains("delivery.rs") || error.contains("DeliveryMoment::default"),
                "{error}"
            );
        }
    }
}
