import { readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

export type LayoutToken = {
  value: number;
  unit: string;
  purpose: string;
  /** Older tokens retain dimension scans until their role is explicit. */
  kind?: "dimension" | "spacing" | "condition";
};
export type LegacyConsumer = {
  path: string;
  kind: string;
  signature: string;
  count: number;
  key: string;
  plannedOwner: string;
  purpose: string;
};
export type LayoutContract = {
  tokens: Record<string, LayoutToken>;
  queries: Record<string, { key: string; operator: string }>;
  legacyConsumers: LegacyConsumer[];
  witnessViewports: {
    width: number;
    height: number;
    safeInsets: { top: number; right: number; bottom: number; left: number };
  }[];
  safeAreaPolicy: Record<string, string>;
};
export const webRoot = fileURLToPath(new URL("../", import.meta.url));
export const ownerPath = "src/layout/layout-contract.json";
export function readLayoutContract(root = webRoot) {
  const source = readFileSync(resolve(root, ownerPath), "utf8");
  // JSON.parse keeps only the last duplicate property. Check object keys first.
  const stack: (Set<string> | null)[] = [];
  for (const match of source.matchAll(/"(?:[^"\\]|\\.)*"|[{}[\]]/g)) {
    const token = match[0];
    if (token === "{" || token === "[")
      stack.push(token === "{" ? new Set() : null);
    else if (token === "}" || token === "]") stack.pop();
    else if (/^\s*:/.test(source.slice(match.index + token.length))) {
      const keys = stack.at(-1);
      const key: string = JSON.parse(token);
      if (keys?.has(key))
        throw new Error(`${ownerPath}: duplicate owner ${key}`);
      keys?.add(key);
    }
  }
  const contract: LayoutContract = JSON.parse(source);
  return contract;
}
export const cssName = (key: string) =>
  `--layout-${key
    .replace(/([a-z])([A-Z])/g, "$1-$2")
    .replaceAll(".", "-")
    .toLowerCase()}`;
export function validateContract(contract: LayoutContract) {
  const units = new Set(["px", "rem", "em", "ms", "ratio", "layer"]);
  for (const [key, token] of Object.entries(contract.tokens)) {
    if (
      !units.has(token.unit) ||
      !Number.isFinite(token.value) ||
      token.value < 0 ||
      !token.purpose ||
      (token.kind !== undefined &&
        !["dimension", "spacing", "condition"].includes(token.kind)) ||
      (token.unit === "ratio" && token.value > 1) ||
      (token.unit === "layer" && !Number.isInteger(token.value))
    )
      throw new Error(`${ownerPath}: invalid owner ${key}`);
  }
  const names = new Set();
  for (const key of Object.keys(contract.tokens)) {
    const name = cssName(key);
    if (names.has(name))
      throw new Error(`${ownerPath}: duplicate owner ${key}`);
    names.add(name);
  }
  for (const [name, query] of Object.entries(contract.queries)) {
    if (
      contract.tokens[query.key]?.unit !== "px" ||
      !["<", "<=", ">", ">="].includes(query.operator)
    )
      throw new Error(`${ownerPath}: invalid query ${name} owner ${query.key}`);
  }
}
const tsObject = (value: unknown) =>
  JSON.stringify(value, null, 2).replace(/^(\s*)"([A-Za-z_]\w*)":/gm, "$1$2:");
export function renderContract(contract: LayoutContract) {
  validateContract(contract);
  const values: Record<string, Record<string, number>> = {};
  for (const [key, token] of Object.entries(contract.tokens)) {
    const [group, name] = key.split(".");
    if (!group || !name) throw new Error(`${ownerPath}: invalid owner ${key}`);
    (values[group] ??= {})[name] = token.value;
  }
  const queries = Object.fromEntries(
    Object.entries(contract.queries).map(([name, query]) => {
      const token = contract.tokens[query.key];
      if (!token)
        throw new Error(
          `${ownerPath}: invalid query ${name} owner ${query.key}`,
        );
      return [name, `(width ${query.operator} ${token.value}px)`];
    }),
  );
  const ts = `// Generated by scripts/generate-layout-contract.ts. Edit layout-contract.json.\nexport const layoutTokens = ${tsObject(contract.tokens)} as const;\nexport const layoutValues = ${tsObject(values)} as const;\nexport const layoutQueries = ${tsObject(queries)} as const;\nexport const layerZIndex = layoutValues.layers;\nexport type LayoutLengthKey = { [K in keyof typeof layoutTokens]: (typeof layoutTokens)[K]["unit"] extends "px" | "rem" ? K : never }[keyof typeof layoutTokens];\n`;
  const css = `/* Generated by scripts/generate-layout-contract.ts. Edit layout-contract.json. */\n:root {\n${Object.entries(
    contract.tokens,
  )
    .map(
      ([key, t]) =>
        `  ${cssName(key)}: ${t.value}${["px", "rem", "em", "ms"].includes(t.unit) ? t.unit : ""};`,
    )
    .join("\n")}\n}\n`;
  const output: Record<string, string> = {
    "src/layout/layout-contract.generated.ts": ts,
    "src/layout/layout-contract.generated.css": css,
  };
  for (const [file, content] of Object.entries(output)) {
    const result = spawnSync(
      resolve(webRoot, "../../../../node_modules/.bin/oxfmt"),
      ["--stdin-filepath", resolve(webRoot, file), "--threads", "1"],
      { input: content, encoding: "utf8" },
    );
    if (result.status !== 0)
      throw new Error(
        `Cannot format generated consumer ${file}: ${result.stderr ?? result.error}`,
      );
    output[file] = result.stdout;
  }
  return output;
}
export function generateLayoutContract(root = webRoot, check = false) {
  const output = renderContract(readLayoutContract(root));
  for (const [file, content] of Object.entries(output)) {
    const path = resolve(root, file);
    if (check) {
      let actual;
      try {
        actual = readFileSync(path, "utf8");
      } catch {
        actual = "";
      }
      if (actual !== content)
        throw new Error(`${ownerPath}: stale generated consumer ${file}`);
    } else writeFileSync(path, content);
  }
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  generateLayoutContract(webRoot, process.argv.includes("--check"));
